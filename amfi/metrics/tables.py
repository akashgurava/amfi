# ------------------------------------------------------ per-period views


def _period_view_class_name(period: str) -> str:
    """``"2026"`` -> ``"Metrics2026View"``; ``"2026_03"`` -> ``"Metrics202603View"``."""
    return "Metrics" + period.replace("_", "") + "View"


def _freq_of_period(period: str) -> Frequency:
    """Infer the frequency from a period key's shape."""
    parts = period.split("_")
    if len(parts) == 1:
        return "yearly"
    # Monthly periods use zero-padded two-digit month (len == 2); quarterly
    # uses a single digit.
    return "monthly" if len(parts[1]) == 2 else "quarterly"


def _make_period_view(period: str) -> type[DerivedView]:
    """Generate a :class:`DerivedView` for a single period.

    The view selects ``sd_id, scheme`` from :data:`plans` (via
    :class:`amfi.data.derived.PlansView`) and ``LEFT JOIN``s
    ``metrics_basic_<freq>``, ``metrics_risk_<freq>``,
    ``metrics_benchmark_<freq>`` (plus ``metrics_performance_yearly`` when
    yearly), renaming ``<metric>_<period>`` columns to the bare metric name.
    All referenced names come from class ``name()`` methods; no literals.
    """
    from ..derived import PlansView

    freq = _freq_of_period(period)
    groups: list[tuple[type[Table], tuple[str, ...], str]] = [
        (basic_table(freq), _BASIC_METRICS, "b"),
        (risk_table(freq), _RISK_METRICS, "r"),
        (benchmark_table(freq), _BENCHMARK_METRICS, "bm"),
    ]
    if freq == "yearly":
        groups.append((MetricsPerformanceYearlyTable, _PERFORMANCE_METRICS, "pf"))

    view_name = f"metrics_{period}"
    plans_alias = "p"

    class _PeriodView(DerivedView):
        @classmethod
        def name(cls) -> str:
            return view_name

        @classmethod
        def select_sql(cls) -> str:
            select_cols = [
                f"{plans_alias}.sd_id",
                f"{plans_alias}.scheme",
            ]
            joins: list[str] = []
            for tbl, metrics, alias in groups:
                joins.append(
                    f"LEFT JOIN {tbl.name()} {alias} "
                    f"ON {alias}.sd_id = {plans_alias}.sd_id"
                )
                for m in metrics:
                    select_cols.append(f"{alias}.{m}_{period} AS {m}_{period}")
            return (
                f"SELECT {', '.join(select_cols)}\n"
                f"FROM {PlansView.name()} {plans_alias}\n" + "\n".join(joins)
            )

    _PeriodView.__name__ = _period_view_class_name(period)
    _PeriodView.__qualname__ = _PeriodView.__name__
    return _PeriodView


def _all_period_view_classes() -> tuple[type[DerivedView], ...]:
    """Build one :class:`DerivedView` per (freq, period) in default config."""
    cfg = MetricsConfig()
    seen: dict[str, type[DerivedView]] = {}
    for freq in _FREQUENCIES:
        for period in cfg.periods(freq):
            if period in seen:
                continue
            seen[period] = _make_period_view(period)
    return tuple(seen.values())


METRICS_PERIOD_VIEWS: tuple[type[DerivedView], ...] = _all_period_view_classes()


